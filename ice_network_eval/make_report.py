"""Generates records/REPORT_TABLES.md (all numbers) from the per-run-record summaries. Prose lives in EVALUATION_REPORT.md; this file prevents transcription errors.
python make_report.py"""
import glob, json, os, subprocess, sys
import numpy as np
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
import analyze_campaign as A
R = lambda n: os.path.join(HERE, "records", n)
L = []
def P(*a): L.append(" ".join(str(x) for x in a))
def f(x, n=3):
    if x is None: return "-"
    if isinstance(x, str): return x
    return f"{x:.{n}g}"
def table(head, rows):
    P("| " + " | ".join(head) + " |"); P("|" + "---|" * len(head))
    for r in rows: P("| " + " | ".join(str(c) for c in r) + " |")
    P()

man = json.load(open(R("manifest.json"))) if os.path.exists(R("manifest.json")) else None
P("# Report tables (generated by make_report.py from immutable per-run records)\n")
if man: P(f"Manifest: {man['counts']}; summed per-run wall time {man['total_wall_s']/3600:.2f} h (concurrent workers, so not elapsed time).\n")

# ---------------------------------------------------------------- 1 frozen S1-S5
S = json.load(open(R("campaign_summary_frozen.json")))
P("## 1. Reduced network vs resolved reference under shared closures (frozen S1-S5)\n")
P("Target = 400-cell reference; its uncertainty is the 200->400 change (first-order upwind scheme; observed orders in the convergence table). Route = outlet with the larger delivered volume over 8 h. t_dom2 = first time Q_R2 > Q_R1.\n")
rows = []
for scn in ("S1", "S2", "S3", "S4", "S5"):
    v = S[f"{scn}|{{}}"]; t = v["target"]; cv = v["reference_convergence"]
    ru = lambda k: None if cv[k].get("change_fine") is None else abs(cv[k]["change_fine"])
    rows.append([scn, t["route"], f(t["metrics"]["t_act1_s"], 5), f(t["metrics"]["t_act2_s"], 5) + f" (±{f(ru('t_act2_s'),2)})", f(t["metrics"]["t_dom2_s"], 5) + (f" (±{f(ru('t_dom2_s'),2)})" if t["metrics"]["t_dom2_s"] else ""),
                 f"{t['metrics']['sill_lowering1_m']*1e3:.2f} / {t['metrics']['sill_lowering2_m']*1e3:.2f}", f"{t['metrics']['delivered1_m3']:.0f} / {t['metrics']['delivered2_m3']:.0f}", f(v["reference_hydrograph_change"]["200->400"], 3)])
table(["scn", "ref route", "t_act1 (s)", "t_act2 (s, ±ref unc.)", "t_dom2 (s, ±ref unc.)", "sill lowering R1/R2 (mm)", "delivered R1/R2 (m3)", "ref hydrograph change 200->400 (RMSE/I)"], rows)
rows = []
for scn in ("S1", "S2", "S3", "S4", "S5"):
    v = S[f"{scn}|{{}}"]
    for k, b in v["reduced"].items():
        te = b["event_time_error_s"]
        rows.append([scn, k, "yes" if b["route_match"] else "NO", f(b["hydrograph"]["hydrograph_rmse_over_I"], 3), f(b["hydrograph"]["cumvol_err_rel_total"], 3), f(te["t_act2_s"], 4), f(te["t_dom2_s"], 5),
                     f"{b['sill_lowering_err_m'][0]*1e3:+.2f} / {b['sill_lowering_err_m'][1]*1e3:+.2f}", f"{b['conservation']['water_residual_rel']:.1e} / {b['conservation']['energy_residual_rel']:.1e} / {b['conservation']['geometry_vs_latent_rel_max']:.1e} ({b['conservation'].get('geometry_vs_latent_kg_abs_max', float('nan')):.1e} kg)", f(b["solver_s"], 3), f(b["peak_rss_mb"], 3)])
table(["scn", "reduced", "route ok", "hydrograph RMSE/I", "cum. volume err (rel total)", "t_act2 err (s)", "t_dom2 err (s)", "sill err R1/R2 (mm)", "water / energy / geometry-vs-latent resid (rel)", "solver s*", "RSS MB"], rows)
P("*solver seconds measured with two campaign workers concurrently on 4 cores; see the serial timing section.\n")

# ---------------------------------------------------------------- 2 closure
if os.path.exists(R("closure_summary.json")):
    C = json.load(open(R("closure_summary.json")))
    P("## 2. Sensitivity to physical closures (reference 200 cells; closure applied to reference and reduced alike)\n")
    rows = []
    for scn, vs in C.items():
        for v, row in vs.items():
            vb = row.get("vs_base", {})
            rows.append([scn, v, row["route"], f(row["t_act2_s"], 4), f(row["t_dom2_s"], 5), f"{row['sill_lowering_m'][0]*1e3:.1f} / {row['sill_lowering_m'][1]*1e3:.1f}",
                         "-" if not vb else ("changed" if vb["route_changed"] else "same"), "-" if not vb else f(vb["t_act2_shift_s"], 3), "-" if not vb else ("appears/disappears" if vb["t_dom2_appears_or_disappears"] else f(vb["t_dom2_shift_s"], 4)),
                         "-" if not vb else "%.2f / %.2f" % tuple(vb["sill_lowering_ratio"]), f(row.get("r17_matched_closure_error", {}).get("hydrograph_rmse_over_I"), 3)])
    table(["scn", "closure", "route", "t_act2 (s)", "t_dom2 (s)", "sill lowering R1/R2 (mm)", "route vs base", "t_act2 shift (s)", "t_dom2 shift (s)", "incision ratio R1/R2 vs base", "r17 matched-closure hydrograph RMSE/I"], rows)

# ---------------------------------------------------------------- 3 convergence
if os.path.exists(R("convergence_summary.json")):
    K = json.load(open(R("convergence_summary.json")))
    P("## 3. One-factor convergence (baseline r17, dt_geom 450 s, msub 16, rtol 1e-7; target = 800-cell reference)\n")
    for scn, v in K.items():
        u = v["reference_uncertainty_400_to_800"]
        P(f"**{scn}**: reference uncertainty (400->800 change): hydrograph RMSE/I {f(u['hydrograph_rmse_over_I'],3)}, t_act2 {f(u['t_act2_s'],3)} s, t_dom2 {f(u['t_dom2_s'],4)} s, sill lowering R1/R2 {f(u['sill_lowering1_m']*1e3,2)} / {f(u['sill_lowering2_m']*1e3,2)} mm.\n")
        rows = []
        for fac, rs in v["sweeps"].items():
            for x in rs: rows.append([fac, f(x["value"], 4), f(x["hydrograph_rmse_over_I"], 3), f(x.get("observed_order_vs_previous"), 2), f(x["t_act2_err_s"], 3), f(x["t_dom2_err_s"], 4), f"{x['sill_err_m'][0]*1e3:+.2f} / {x['sill_err_m'][1]*1e3:+.2f}", f(x["solver_s"], 3), x["law_evals"]])
        table(["factor", "value", "hydrograph RMSE/I", "observed order vs previous", "t_act2 err (s)", "t_dom2 err (s)", "sill err R1/R2 (mm)", "solver s*", "law evals"], rows)

# ---------------------------------------------------------------- 4/5 sets
for name in ("param_dev", "param_eval", "challenge"):
    if os.path.exists(R(f"set_summary_{name}.json")):
        T = json.load(open(R(f"set_summary_{name}.json")))["aggregate"]
        P(f"## Set `{name}`\n"); P("```"); P(json.dumps(T, indent=1)); P("```\n")
if os.path.exists(R("baseline_summary.json")):
    B = json.load(open(R("baseline_summary.json"))); P("## Evolving-channel baselines on the frozen problems (target: thermal reference 400 cells)\n"); table(B["head"], B["rows"])
if os.path.exists(R("timing_serial_summary.json")):
    T = json.load(open(R("timing_serial_summary.json"))); P("## Serial repeated timings (one worker, idle machine)\n"); table(T["head"], T["rows"])
open(R("REPORT_TABLES.md"), "w").write("\n".join(L)); print("wrote", R("REPORT_TABLES.md"), len(L), "lines")
